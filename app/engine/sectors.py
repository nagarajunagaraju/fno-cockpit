INDEX_NIFTY = "NIFTY 50"
INDEX_BANKNIFTY = "NIFTY BANK"

SECTOR_OF: dict[str, str] = {}
for _idx, _syms in _GROUPS.items():
    for _s in _syms.split():
        SECTOR_OF.setdefault(_s, _idx)

_override = Path(__file__).resolve().parents[2] / "data" / "sector_map.json"
if _override.exists():
    try:
        SECTOR_OF.update(json.loads(_override.read_text(encoding="utf-8")))
    except Exception:  # bad file -> keep built-in map, the health screen shows the error
        pass


def sector_of(symbol: str) -> str:
    return SECTOR_OF.get(symbol, "UNMAPPED")


def sector_indices() -> list[str]:
    return sorted(set(SECTOR_OF.values()) | {INDEX_NIFTY, INDEX_BANKNIFTY})


_GROUPS_CAP = {"NIFTY BANK": "FINANCIALS", "NIFTY PSU BANK": "FINANCIALS", "NIFTY FIN SERVICE": "FINANCIALS",
               "NIFTY PHARMA": "HEALTH", "NIFTY HEALTHCARE": "HEALTH"}


def risk_group(symbol: str) -> str:
    """Correlated bucket for the sector cap (banks + financials count as one bet)."""
    s = sector_of(symbol)
    return _GROUPS_CAP.get(s, s)
